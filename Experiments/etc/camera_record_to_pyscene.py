"""
camera_record_to_pyscene.py

ErrorMeasurePass가 기록한 카메라 CSV를 읽어
pyscene에 붙여넣을 수 있는 keyframe 코드를 생성한다.

사용법:
    python camera_record_to_pyscene.py <csv_path> [--stride N] [--duration D] [--out out.py]

옵션:
    --stride N     N프레임마다 keyframe 1개 샘플링 (기본값: 6, 약 10fps @ 60fps)
    --duration D   애니메이션 전체 길이(초). 미지정 시 CSV의 마지막 프레임 인덱스 / fps로 추정
    --fps F        원본 기록 fps 추정값 (기본값: 60). duration 자동 계산에만 사용됨
    --out PATH     출력 파일 경로 (기본값: stdout)
"""

import argparse
import csv
import sys


def load_csv(path: str) -> list[dict]:
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
    return rows


def sample_rows(rows: list[dict], stride: int) -> list[dict]:
    """stride 간격으로 샘플링. 마지막 프레임은 항상 포함."""
    sampled = rows[::stride]
    if rows and rows[-1] is not sampled[-1]:
        sampled.append(rows[-1])
    return sampled


def estimate_duration(rows: list[dict], fps: float) -> float:
    if not rows:
        return 0.0
    last_frame = int(rows[-1]["frame"])
    return last_frame / fps


def build_pyscene_code(sampled: list[dict], duration: float) -> str:
    lines = []
    lines.append("# --- Camera animation (auto-generated by camera_record_to_pyscene.py) ---")
    lines.append(f"_cam_anim = sceneBuilder.createAnimation(camera, 'recorded', {duration:.4f})")
    lines.append("")

    first_frame = int(sampled[0]["frame"])
    last_frame  = int(sampled[-1]["frame"])
    frame_span  = last_frame - first_frame if last_frame != first_frame else 1

    for row in sampled:
        frame   = int(row["frame"])
        # keyframe 시각: 0.0 ~ duration 으로 선형 매핑
        t       = (frame - first_frame) / frame_span * duration

        pos_x, pos_y, pos_z       = row["pos_x"],    row["pos_y"],    row["pos_z"]
        tgt_x, tgt_y, tgt_z       = row["target_x"], row["target_y"], row["target_z"]
        up_x,  up_y,  up_z        = row["up_x"],     row["up_y"],     row["up_z"]

        lines.append(
            f"_cam_anim.addKeyframe({t:.4f}, Transform("
            f"position=float3({pos_x}, {pos_y}, {pos_z}), "
            f"target=float3({tgt_x}, {tgt_y}, {tgt_z}), "
            f"up=float3({up_x}, {up_y}, {up_z})))"
        )

    lines.append("")
    lines.append("# CameraController 입력을 비활성화해야 재현이 deterministic함 (이슈 1)")
    lines.append("# m.scene.setCameraControlsEnabled(False)")
    lines.append("# --- End camera animation ---")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Convert camera CSV to pyscene keyframe code.")
    parser.add_argument("csv_path", help="ErrorMeasurePass가 출력한 카메라 CSV 파일 경로")
    parser.add_argument("--stride",   type=int,   default=6,    help="샘플링 간격 (기본값: 6)")
    parser.add_argument("--duration", type=float, default=None, help="애니메이션 길이(초). 미지정 시 자동 추정")
    parser.add_argument("--fps",      type=float, default=60.0, help="원본 기록 fps (기본값: 60)")
    parser.add_argument("--out",      type=str,   default=None, help="출력 파일 경로 (기본값: stdout)")
    args = parser.parse_args()

    rows = load_csv(args.csv_path)
    if not rows:
        print("ERROR: CSV가 비어 있습니다.", file=sys.stderr)
        sys.exit(1)

    sampled  = sample_rows(rows, args.stride)
    duration = args.duration if args.duration is not None else estimate_duration(rows, args.fps)

    code = build_pyscene_code(sampled, duration)

    if args.out:
        with open(args.out, "w") as f:
            f.write(code)
        print(f"생성 완료: {args.out}  (keyframe {len(sampled)}개, duration={duration:.2f}s)")
    else:
        print(code)


if __name__ == "__main__":
    main()
